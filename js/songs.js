const BEAT_WORDS = {
  3: ["Раз", "Два", "Три"],
  4: ["Раз", "Два", "Три", "Четыре"],
};

export function songFigure(song) {
  return song.notes.map((name, index) => ({
    name,
    beats: song.rhythm?.[index] ?? 1,
  }));
}

export function beatWord(meter, index) {
  const words = BEAT_WORDS[meter] || BEAT_WORDS[4];
  return words[((index % words.length) + words.length) % words.length];
}

export function songSpan(song) {
  const midis = song.notes.map(nameToMidi);
  return { low: Math.min(...midis), high: Math.max(...midis) };
}

export function songFits(song, start, end) {
  const span = songSpan(song);
  return span.low >= start && span.high <= end;
}
